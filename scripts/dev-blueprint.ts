/**
 * bun run dev:blueprint <path-to-blueprint.html>
 *
 * Builds the private /dev page from a blueprint HTML export:
 *  1. Scopes the blueprint's stylesheet under `.bp` and writes src/styles/dev-blueprint.css
 *     (design only, nothing confidential).
 *  2. Encrypts the document body with AES-256-GCM and writes src/content/dev/blueprint.enc.json.
 *
 * The key is derived from the gate email + password with scrypt (memory-hard), so the repo
 * (which is public) only ever holds ciphertext. The server decrypts it only when the right
 * email and password are entered; a wrong pair fails the GCM tag check.
 *
 * Credentials are read from the environment, never from the command line or the repo:
 *   DEV_GATE_EMAIL=... DEV_GATE_PASSWORD=... bun run dev:blueprint ./Puntr_MVP_Blueprint.html
 * Changing the password = re-running this script with the new one and committing both files.
 */
import { createCipheriv, createHash, randomBytes } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, basename } from "node:path";
import postcss, { type Rule, type AtRule } from "postcss";

import { deriveDevKey, DEV_KDF } from "../src/lib/dev-gate.crypto";

const ROOT = join(import.meta.dirname, "..");
const CSS_OUT = join(ROOT, "src/styles/dev-blueprint.css");
const ENC_OUT = join(ROOT, "src/content/dev/blueprint.enc.json");

const src = process.argv[2];
const email = process.env["DEV_GATE_EMAIL"];
const password = process.env["DEV_GATE_PASSWORD"];
if (!src || !email || !password) {
  console.error(
    "Usage: DEV_GATE_EMAIL=… DEV_GATE_PASSWORD=… bun run dev:blueprint <blueprint.html>",
  );
  process.exit(1);
}

const html = readFileSync(src, "utf8");

// ---------- 1. Stylesheet ----------
const styles = [...html.matchAll(/<style>([\s\S]*?)<\/style>/g)].map((m) => m[1] ?? "");
const blueprintCss = styles.find((s) => s.includes("--green")) ?? "";
if (!blueprintCss) throw new Error("Blueprint stylesheet not found");

const root = postcss.parse(blueprintCss);
root.walkAtRules("media", (at: AtRule) => {
  // The site is light-only; drop the dark scheme.
  if (at.params.includes("prefers-color-scheme")) at.remove();
});
root.walkRules((rule: Rule) => {
  const parent = rule.parent;
  if (parent && parent.type === "atrule" && /keyframes/.test((parent as AtRule).name)) return;
  if (rule.selector.includes('data-theme="dark"')) {
    rule.remove();
    return;
  }
  rule.selectors = rule.selectors.map((sel) => {
    const s = sel.trim();
    if (s === ":root" || s === "html" || s === "body") return ".bp";
    if (/^(\*|\*::before|\*::after)$/.test(s)) return `.bp ${s}`;
    return `.bp ${s}`;
  });
});
mkdirSync(dirname(CSS_OUT), { recursive: true });
writeFileSync(
  CSS_OUT,
  `/* Generated by scripts/dev-blueprint.ts from ${basename(src)}. Do not edit by hand.\n` +
    ` * Blueprint styles, scoped to .bp so they never leak into the site. Light only. */\n` +
    root.toString().trim() +
    "\n",
);

// ---------- 2. Body ----------
const bodyStart = html.indexOf("<body>");
const scriptStart = html.lastIndexOf("<script>");
if (bodyStart < 0) throw new Error("<body> not found");
let body = html.slice(
  bodyStart + "<body>".length,
  scriptStart > bodyStart ? scriptStart : undefined,
);
body = body
  .replace(/<title>[\s\S]*?<\/title>/g, "")
  .replace(/<meta[^>]*>/g, "")
  .replace(/<link[^>]*>/g, "")
  .replace(/<style>[\s\S]*?<\/style>/g, "")
  .replace(/<\/body>[\s\S]*$/g, "")
  // External links open in a new tab without leaking the referrer.
  .replace(/<a href="(https?:[^"]+)"/g, '<a href="$1" target="_blank" rel="noopener noreferrer"')
  .trim();

// Known export glitch: some wrapper divs lose their opening tag and leave an empty line behind
// (the readiness verdict's right column, the KPI tiles and the score rows). Put them back.
body = body.replace(
  /(<div class="verdict">\s*<div class="vl">[\s\S]*?<\/div>)(\n[ \t]*\n\s*)(<p>)/,
  (_m, vl: string, ws: string, p: string) => `${vl}${ws}<div class="vr">${p}`,
);
body = body.replace(/\n[ \t]*\n(\s*)(<div class="tile">)/, '\n<div class="tiles">\n$1$2');
body = body.replace(/\n[ \t]*\n(\s*)(<div class="srow">)/, '\n<div class="score">\n$1$2');

// The HTML is injected into a React tree, so it must be well-formed: an unbalanced tag makes the
// browser re-nest the page and breaks hydration. Fail the build instead of shipping that.
if (process.env["DEV_DUMP"]) writeFileSync(process.env["DEV_DUMP"], body);
assertBalanced(body);

function assertBalanced(markup: string) {
  const VOID = new Set(["br", "img", "meta", "link", "input", "hr", "wbr", "source", "col"]);
  const stack: Array<{ tag: string; line: number }> = [];
  const re = /<(\/?)([a-zA-Z][a-zA-Z0-9-]*)\b[^>]*?(\/?)>/g;
  const stripped = markup.replace(/<pre\b[\s\S]*?<\/pre>/g, (pre) =>
    pre.replace(/<(?!\/?pre\b)/g, "&lt;"),
  );
  let m: RegExpExecArray | null;
  while ((m = re.exec(stripped))) {
    const [, close, rawTag, selfClose] = m;
    const tag = (rawTag ?? "").toLowerCase();
    const line = stripped.slice(0, m.index).split("\n").length;
    if (VOID.has(tag) || selfClose || tag.includes(":")) continue;
    if (!close) stack.push({ tag, line });
    else {
      const top = stack.pop();
      if (!top || top.tag !== tag) {
        throw new Error(
          `Unbalanced HTML: </${tag}> on line ${line} closes <${top?.tag ?? "nothing"}> from line ${top?.line ?? "-"}`,
        );
      }
    }
  }
  if (stack.length)
    throw new Error(`Unclosed <${stack.at(-1)?.tag}> from line ${stack.at(-1)?.line}`);
}

const salt = randomBytes(16);
const iv = randomBytes(12);
const key = deriveDevKey(email, password, salt);
const cipher = createCipheriv("aes-256-gcm", key, iv);
const data = Buffer.concat([cipher.update(body, "utf8"), cipher.final()]);
const tag = cipher.getAuthTag();

mkdirSync(dirname(ENC_OUT), { recursive: true });
writeFileSync(
  ENC_OUT,
  JSON.stringify(
    {
      v: 1,
      kdf: DEV_KDF,
      salt: salt.toString("base64"),
      iv: iv.toString("base64"),
      tag: tag.toString("base64"),
      sha256: createHash("sha256").update(body).digest("hex"),
      source: basename(src),
      builtAt: new Date().toISOString(),
      data: data.toString("base64"),
    },
    null,
    0,
  ) + "\n",
);
console.log(`Wrote ${CSS_OUT} and ${ENC_OUT} (${body.length} chars of HTML)`);
